create role anon;
create role authenticated;
create schema auth;
create function auth.uid() returns uuid language sql stable as $$ select null::uuid $$;

create table public.site (
  id text primary key,
  data jsonb not null
);
create table public.stock (
  pid text primary key,
  qty integer not null,
  updated_at timestamptz not null default now()
);
create table public.orders (
  id uuid primary key default gen_random_uuid(),
  code text unique not null,
  data jsonb not null,
  created_at timestamptz not null default now()
);
create table public.chat_messages (
  id bigint generated by default as identity primary key,
  uid text,
  name text,
  avatar text,
  text text,
  image text,
  is_admin boolean not null default false,
  edited boolean,
  reply_to bigint,
  rname text,
  rtext text,
  created_at timestamptz not null default now()
);
create table public.draw_entries (
  id bigserial primary key
);
create table public.stock_notify (
  id bigserial primary key
);
create table public.story_comments (
  id bigserial primary key,
  story_id text,
  name text,
  text text,
  avatar text,
  uid text,
  is_admin boolean,
  edited boolean,
  reply_to bigint,
  rname text,
  rtext text,
  created_at timestamptz not null default now()
);
alter table public.story_comments enable row level security;

alter table public.orders enable row level security;
create policy "orders insert" on public.orders for insert to anon, authenticated with check (true);

create function public.stock_on_order() returns trigger
language plpgsql as $$ begin return new; end $$;
create function public.stock_on_status() returns trigger
language plpgsql as $$ begin return new; end $$;
create trigger stock_on_order_t after insert on public.orders
for each row execute function public.stock_on_order();
create trigger stock_on_status_t after update on public.orders
for each row execute function public.stock_on_status();

